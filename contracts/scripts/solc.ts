// Shared solc-js compilation for the compile script, the contract tests and the on-chain checks.
// PortalDot V3's Revive pallet reports allowEVMBytecode = true, so standard solc output is the target.
import { readdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import type { Abi, Hex } from "viem";

const require = createRequire(import.meta.url);
const solc = require("solc") as { version(): string; compile(input: string): string };

export const EVM_VERSION = process.env.SOLC_EVM_VERSION || "cancun";
export const SOLC_VERSION = solc.version();
export const CONTRACTS_ROOT = join(import.meta.dirname, "..");

/** AST id of an immutable variable to the byte ranges it occupies in the runtime code. */
export type ImmutableReferences = Record<string, { start: number; length: number }[]>;

export interface CompiledContract {
  contractName: string;
  sourceName: string;
  abi: Abi;
  bytecode: Hex;
  deployedBytecode: Hex;
  /** Byte ranges of the runtime code that the constructor fills with immutable values. */
  immutableReferences: ImmutableReferences;
}

/**
 * Reads every .sol file in the given directories (relative to contracts/), keyed by bare file name, so
 * one file imports another as `import {X} from "X.sol"` wherever it lives. Names must be unique.
 */
export function readSources(...dirs: string[]): Record<string, { content: string }> {
  const sources: Record<string, { content: string }> = {};
  for (const dir of dirs) {
    for (const file of readdirSync(join(CONTRACTS_ROOT, dir)).filter((f) => f.endsWith(".sol"))) {
      if (sources[file]) throw new Error(`Two sources are named ${file}`);
      sources[file] = { content: readFileSync(join(CONTRACTS_ROOT, dir, file), "utf8") };
    }
  }
  return sources;
}

/** Compiles the sources; throws with every error message if any source fails. Warnings are returned. */
export function compile(sources: Record<string, { content: string }>): { contracts: CompiledContract[]; warnings: string[] } {
  const output = JSON.parse(
    solc.compile(
      JSON.stringify({
        language: "Solidity",
        sources,
        settings: {
          evmVersion: EVM_VERSION,
          optimizer: { enabled: true, runs: 200 },
          outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "evm.deployedBytecode.immutableReferences"] } },
        },
      }),
    ),
  ) as {
    errors?: { severity: string; formattedMessage: string }[];
    contracts?: Record<
      string,
      Record<string, { abi: Abi; evm: { bytecode: { object: string }; deployedBytecode: { object: string; immutableReferences?: ImmutableReferences } } }>
    >;
  };
  const errors = (output.errors ?? []).filter((e) => e.severity === "error").map((e) => e.formattedMessage);
  if (errors.length > 0) throw new Error(errors.join("\n"));
  const contracts = Object.entries(output.contracts ?? {}).flatMap(([sourceName, byName]) =>
    Object.entries(byName).map(([contractName, c]) => ({
      contractName,
      sourceName,
      abi: c.abi,
      bytecode: `0x${c.evm.bytecode.object}` as Hex,
      deployedBytecode: `0x${c.evm.deployedBytecode.object}` as Hex,
      immutableReferences: c.evm.deployedBytecode.immutableReferences ?? {},
    })),
  );
  return { contracts, warnings: (output.errors ?? []).filter((e) => e.severity !== "error").map((e) => e.formattedMessage) };
}

/** Typed ABI for TypeScript consumers, written to abi/<Name>.ts. Generated: do not edit by hand; re-run `pnpm compile`. */
export function typedAbiSource(c: CompiledContract): string {
  const constName = `${c.contractName[0]?.toLowerCase()}${c.contractName.slice(1)}Abi`;
  return `// Generated by contracts/scripts/compile.ts from ${c.sourceName} (solc ${SOLC_VERSION}). Do not edit.\nexport const ${constName} = ${JSON.stringify(c.abi, null, 2)} as const;\n`;
}

/**
 * The runtime code a deployment will hold: the compiled runtime with each immutable's 32-byte value
 * written over its placeholder ranges. `values` maps the immutable's AST id to its ABI-encoded word.
 */
export function runtimeWithImmutables(contract: Pick<CompiledContract, "deployedBytecode" | "immutableReferences">, values: Record<string, Hex>): Hex {
  const code = contract.deployedBytecode.slice(2).split("");
  for (const [id, ranges] of Object.entries(contract.immutableReferences)) {
    const word = values[id];
    if (!word || !/^0x[0-9a-f]{64}$/.test(word)) throw new Error(`No 32-byte value given for immutable ${id}`);
    for (const { start, length } of ranges) code.splice(start * 2, length * 2, ...word.slice(2, 2 + length * 2).split(""));
  }
  return `0x${code.join("")}`;
}
